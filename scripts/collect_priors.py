"""Seed data for the goal priors (Phase 67): the full library plays every public game (5 seeds,
4,000 actions); at each level-up the features of the hypotheses on the screen, and of those that
ended the level, are counted per game; the counts, averaged over seeds, are written to
neo4/priors_data.py. usage: PYTHONHASHSEED=0 python scripts/collect_priors.py"""

import logging
import sys
from collections import Counter, defaultdict
from multiprocessing import Pool
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
logging.disable(logging.INFO)

from neo4 import shared  # noqa: E402
from neo4.library import LibraryAgent  # noqa: E402
from neo4.model_agent import ModelAgent  # noqa: E402
from neo4.run import PUBLIC_GAMES, play  # noqa: E402


def job(args: tuple[str, int]) -> dict:
    game, seed = args
    shared.reset()
    ModelAgent.share_priors = True
    ModelAgent.seed_priors = False  # count this game alone
    play("library", game, seed, 4000, agent=LibraryAgent(seed=seed), label="collect")
    p = shared.goal_priors()
    return {"game": game, "levels": p.levels, "seen": dict(p.seen), "ended": dict(p.ended)}


def main() -> None:
    jobs = [(g, s) for g in PUBLIC_GAMES for s in range(5)]
    with Pool(4, maxtasksperchild=1) as pool:
        rows = pool.map(job, jobs)
    by: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by[r["game"]].append(r)
    out = ROOT / "neo4" / "priors_data.py"
    with out.open("w") as f:
        f.write('"""What the goals were like at the level-ups the full library reaches on the public games\n'
                "(Phase 67): per game, its level-ups and the counts of hypothesis features seen at a\n"
                "level's end and of those that ended it, averaged over five seeds. Generated by\n"
                'scripts/collect_priors.py; read by shared.seed_from_public."""\n\n')
        f.write("COUNTS = {\n")
        for g, rs in sorted(by.items()):
            k = len(rs)
            seen: Counter = Counter()
            ended: Counter = Counter()
            for r in rs:
                seen.update(r["seen"])
                ended.update(r["ended"])
            levels = round(sum(r["levels"] for r in rs) / k)
            s = sorted((ft, round(n / k)) for ft, n in seen.items() if round(n / k))
            e = sorted((ft, round(n / k)) for ft, n in ended.items() if round(n / k))
            f.write(f"    {g!r}: {(levels, s, e)!r},\n")
        f.write("}\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
