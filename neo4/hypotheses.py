"""Goal hypotheses read from the screen, and a memory of what each action does to them (Phase 59).

A person facing a new level guesses its goal from the screen and tests the guess; the explorer
instead tries actions until a level happens to end. This module supplies guesses of the kinds a
person makes first, each with a measure of how far the screen is from it, so that the agent can
learn which actions move which measure and steer by the ones that move:

* ``reach``: the player is to reach a kind seen once (an exit, a door, a marked cell);
  measured by the distance between the player and it;
* ``clear``: every object of a kind is to go (collected, removed, matched away); measured by
  how many are left;
* ``match``: two panels of the same size are to become the same (a reference and a board);
  measured by the number of cells in which they differ;
* ``unify``: objects of one shape are to take one colour; measured by how many colours they show;
* ``copy``: a board is to look like a picture elsewhere on the screen, the same size or k times
  smaller, or like its own mirror image; measured by the board's cells that differ from their
  places in the picture. These are not guessed from the first frame but read from what clicks
  change (Phase 62): a click whose changed cells came to agree with unchanged cells elsewhere,
  by one rule of correspondence, is evidence for that rule.

Phase 69 adds guesses generated by what actions turn out to do, as a person forms them on
seeing something happen (``from_events``):

* ``bring``: a kind that moved (and does not move by itself) is to be brought to something: an
  object of its colour, a kind seen once, or another of its own kind; measured by the gap;
* ``paint``: a shape seen to change colour is to show no object left in one of its two colours;
  measured by how many still do (unlike ``unify``, every change counts);
* ``clear``: a kind seen to vanish, if not guessed already.

Nothing here is specific to a public game: the guesses come from the structure of the first frame
of a level (rarity, repetition, equal sizes) or from what an action changed, and none is kept that
no action has ever moved.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field

import numpy as np

from .objects import Diff, Obj

MAX_CLEAR_KINDS = 6  # kinds with several instances proposed as "clear", the most numerous first
MAX_REACH = 6  # single-instance kinds proposed as "reach", the smallest first
MIN_PANEL = 3  # a panel's smaller side, in cells
MAX_PANELS = 12
COPY_SCALES = (1, 2, 3, 4, 8)  # a picture the board's size, or this many times smaller
COPY_MAX_CELLS = 64  # changed cells read per click
COPY_MIN_GAIN = 4  # cells a rule must have brought into agreement, over the level's clicks
COPY_MIN_CLICKS = 2  # ...in at least this many clicks
BRING_SINGLES = 3  # kinds seen once that a moved kind may be meant to reach, the smallest first


@dataclass(slots=True)
class Hypothesis:
    """A guess at a level's goal: a kind, its parameters, and the measure's value when met."""

    kind: str  # reach | clear | match | unify | copy | bring | paint
    params: tuple
    goal: int = 0
    first: int | None = None  # the measure when the level began
    best: int | None = None  # the lowest value seen in this level
    features: tuple = ()  # what it is like, in terms any game shares (Phase 65)
    event: bool = False  # generated by what an action did, not read from the first frame (Phase 69)

    @property
    def key(self) -> tuple:
        return (self.kind, self.params)


def background(grid: np.ndarray) -> int:
    values, counts = np.unique(grid, return_counts=True)
    return int(values[np.argmax(counts)])


def panels(grid: np.ndarray) -> list[tuple[int, int, int, int]]:
    """Rectangles (y1, x1, h, w) of the connected regions of non-background cells, any colour,
    at least MIN_PANEL on each side: the boards, reference pictures and frames of a screen."""
    bg = background(grid)
    mask = grid != bg
    seen = np.zeros_like(mask)
    out = []
    h, w = mask.shape
    for y in range(h):
        for x in range(w):
            if not mask[y, x] or seen[y, x]:
                continue
            stack, ys, xs = [(y, x)], [], []
            seen[y, x] = True
            while stack:
                cy, cx = stack.pop()
                ys.append(cy)
                xs.append(cx)
                for ny, nx in ((cy + 1, cx), (cy - 1, cx), (cy, cx + 1), (cy, cx - 1)):
                    if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:
                        seen[ny, nx] = True
                        stack.append((ny, nx))
            y1, x1, y2, x2 = min(ys), min(xs), max(ys), max(xs)
            if y2 - y1 + 1 >= MIN_PANEL and x2 - x1 + 1 >= MIN_PANEL:
                out.append((y1, x1, y2 - y1 + 1, x2 - x1 + 1))
    out.sort(key=lambda r: (-(r[2] * r[3]), r))
    return out[:MAX_PANELS]


def _bucket(n: int, edges: tuple[int, ...]) -> int:
    """The index of the first edge n does not exceed (len(edges) past the last)."""
    return next((i for i, e in enumerate(edges) if n <= e), len(edges))


def _size_vs(o: Obj, me: Obj) -> str:
    return "same" if o.area == me.area else ("smaller" if o.area < me.area else "larger")


def propose(objs: list[Obj], grid: np.ndarray, avatar_sig: tuple | None) -> list[Hypothesis]:
    """Guesses from a level's first frame, each with features any game shares (Phase 65): its
    kind, whether the keys move an avatar, and how its object looks beside the others and the
    avatar. What the goal turned out to be in other games is kept in these terms."""
    free = [o for o in objs if not o.scenery]
    counts = Counter(o.sig for o in free)
    me = next((o for o in free if o.sig == avatar_sig), None) if avatar_sig is not None else None
    style = "avatar" if me is not None else "click"
    out: list[Hypothesis] = []
    singles = sorted((o for o in free if counts[o.sig] == 1 and o.sig != avatar_sig),
                     key=lambda o: (o.area, o.y1, o.x1))
    for rank, o in enumerate(singles[:MAX_REACH]):
        f = [("reach", style), ("reach", "rank", min(rank, 3)), ("reach", "hollow", o.area < o.w * o.h)]
        if me is not None:
            f += [("reach", "colour of avatar", o.color == me.color), ("reach", "size", _size_vs(o, me))]
        out.append(Hypothesis("reach", (o.sig,), features=tuple(f)))
    many = sorted((s for s, n in counts.items() if 2 <= n <= 40 and s != avatar_sig),
                  key=lambda s: (-counts[s], repr(s)))
    for rank, s in enumerate(many[:MAX_CLEAR_KINDS]):
        one = next(o for o in free if o.sig == s)
        f = [("clear", style), ("clear", "rank", min(rank, 3)), ("clear", "count", _bucket(counts[s], (2, 3, 8))),
             ("clear", "area", _bucket(one.area, (1, 9)))]
        if me is not None:
            f += [("clear", "colour of avatar", one.color == me.color), ("clear", "size", _size_vs(one, me))]
        out.append(Hypothesis("clear", (s,), features=tuple(f)))
    shapes = Counter(o.sig[1:] for o in free)
    for shape, n in sorted(shapes.items(), key=lambda kv: (-kv[1], repr(kv[0]))):
        if n >= 3 and len({o.color for o in free if o.sig[1:] == shape}) >= 2:
            f = (("unify", style), ("unify", "count", _bucket(n, (3, 8))))
            out.append(Hypothesis("unify", (shape,), goal=1, features=f))
    rects = panels(grid)
    for i, a in enumerate(rects):
        for b in rects[i + 1:]:
            if a[2:] == b[2:] and not np.array_equal(_cut(grid, a), _cut(grid, b)):
                same = set(np.unique(_cut(grid, a))) == set(np.unique(_cut(grid, b)))
                f = (("match", style), ("match", "area", _bucket(a[2] * a[3], (16, 100))), ("match", "same colours", same))
                out.append(Hypothesis("match", (a, b), features=f))
    return out


def _cut(grid: np.ndarray, r: tuple[int, int, int, int]) -> np.ndarray:
    y, x, h, w = r
    return grid[y:y + h, x:x + w]


def measure(h: Hypothesis, objs: list[Obj], grid: np.ndarray, me: Obj | None) -> int | None:
    """How far the screen is from the hypothesis (``h.goal`` when met); None when unmeasurable."""
    if h.kind == "reach":
        if me is None:
            return None
        targets = [o for o in objs if o.sig == h.params[0]]
        if not targets:
            return 0  # entered or taken
        return min(_gap(me, t) for t in targets)
    if h.kind == "clear":
        return sum(1 for o in objs if o.sig == h.params[0])
    if h.kind == "unify":
        colours = {o.color for o in objs if not o.scenery and o.sig[1:] == h.params[0]}
        return max(1, len(colours))
    if h.kind == "match":
        a, b = h.params
        return int((_cut(grid, a) != _cut(grid, b)).sum())
    if h.kind == "copy":
        return copy_measure(h.params, grid)
    if h.kind == "bring":
        return bring_measure(h.params, objs)
    if h.kind == "paint":
        shape, colour = h.params
        return sum(1 for o in objs if not o.scenery and o.sig[1:] == shape and o.color == colour)
    return None


# -- guesses generated by what actions did (Phase 69) -----------------------------------------

def bring_measure(params: tuple, objs: list[Obj]) -> int | None:
    """The gap between a moved kind and what it is to be brought to: for each of its objects the
    gap to the nearest target, summed; 0 once no target is left (covered, entered or taken)."""
    sig, (rel, *arg) = params
    movers = [o for o in objs if o.sig == sig]
    if not movers:
        return None
    if rel == "meet":
        if len(movers) < 2:
            return 0
        return min(_gap(a, b) for i, a in enumerate(movers) for b in movers[i + 1:])
    if rel == "colour":
        targets = [o for o in objs if not o.scenery and o.color == arg[0] and o.sig != sig]
    else:
        targets = [o for o in objs if o.sig == arg[0]]
    if not targets:
        return 0
    return sum(min(_gap(m, t) for t in targets) for m in movers)


def bring_for(mover: Obj, objs: list[Obj], avatar_sig: tuple | None) -> list[Hypothesis]:
    """The places a kind seen to move may be meant to go: an object of its colour, another of its
    own kind, a kind seen once."""
    free = [o for o in objs if not o.scenery and o.sig != avatar_sig]
    out = []
    if any(o.color == mover.color and o.sig != mover.sig for o in free):
        out.append(Hypothesis("bring", (mover.sig, ("colour", mover.color)), event=True))
    if sum(1 for o in free if o.sig == mover.sig) >= 2:
        out.append(Hypothesis("bring", (mover.sig, ("meet",)), event=True))
    counts = Counter(o.sig for o in free)
    singles = sorted((o for o in free if counts[o.sig] == 1 and o.sig != mover.sig),
                     key=lambda o: (o.area, o.y1, o.x1))
    out += [Hypothesis("bring", (mover.sig, ("kind", o.sig)), event=True) for o in singles[:BRING_SINGLES]]
    return out


def paint_for(shape: tuple, colours: tuple[int, ...]) -> list[Hypothesis]:
    """A shape seen to change colour: none of it left in each colour it was seen in."""
    return [Hypothesis("paint", (shape, c), event=True) for c in colours]


def from_events(d: Diff, objs: list[Obj], avatar_sig: tuple | None, movers: set[tuple]) -> list[Hypothesis]:
    """Guesses at the goal from what the last action changed: the kinds in ``movers`` (seen to move
    on some actions and stand still on others, not the avatar) that moved, the shapes that changed
    colour, the kinds that vanished."""
    out: list[Hypothesis] = []
    for _, a, _, _ in d.moved:
        if a.sig in movers:
            out += bring_for(a, objs, avatar_sig)
    for b, a in d.recolored:
        if not b.scenery and b.sig[1:] == a.sig[1:]:
            out += paint_for(a.sig[1:], (b.color, a.color))
    for v in d.vanished:
        if v.sig != avatar_sig:
            out.append(Hypothesis("clear", (v.sig,), event=True))
    seen, unique = set(), []
    for h in out:
        if h.key not in seen:
            seen.add(h.key)
            unique.append(h)
    return unique


# -- copies read from what clicks change (Phase 62) -----------------------------------------

def copy_image(rule: tuple, ys: np.ndarray, xs: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Where a rule sends board cells: (``"copy"``, k, dy, dx) to a picture k times smaller at
    (y // k + dy, x // k + dx); (``"mirror-x"``, 1, s, 0) to (y, s - x); (``"mirror-y"``, 1, s, 0)
    to (s - y, x)."""
    kind, k, a, b = rule
    if kind == "copy":
        return ys // k + a, xs // k + b
    if kind == "mirror-x":
        return ys, a - xs
    return a - ys, xs


def _board_cells(rect: tuple[int, int, int, int], rule: tuple, shape: tuple[int, int]):
    y, x, h, w = rect
    ys, xs = np.mgrid[y:y + h, x:x + w]
    ys, xs = ys.ravel(), xs.ravel()
    ty, tx = copy_image(rule, ys, xs)
    ok = (ty >= 0) & (ty < shape[0]) & (tx >= 0) & (tx < shape[1])
    ok &= ~((ty >= y) & (ty < y + h) & (tx >= x) & (tx < x + w))  # the picture lies outside the board
    return ys[ok], xs[ok], ty[ok], tx[ok]


def copy_measure(params: tuple, grid: np.ndarray) -> int | None:
    """The board's cells that differ from their places in the picture."""
    rule, rect = params[:4], params[4]
    ys, xs, ty, tx = _board_cells(rect, rule, grid.shape)
    if not len(ys):
        return None
    return int((grid[ys, xs] != grid[ty, tx]).sum())


def copy_picture_ok(params: tuple, grid: np.ndarray) -> bool:
    """The rule sends most of the board outside it, onto a picture of more than one colour (a
    picture of one colour is no picture: any changed cell of that colour would agree with it)."""
    rule, rect = params[:4], params[4]
    ys, xs, ty, tx = _board_cells(rect, rule, grid.shape)
    return 2 * len(ys) >= rect[2] * rect[3] and len(np.unique(grid[ty, tx])) >= 2


@dataclass
class CopyEvidence:
    """What a level's clicks have said for each rule of correspondence: for every rule, the changed
    cells it brought into agreement, by their new colour, less those it took out of agreement, and
    the clicks that spoke for it. One click paints one colour, which agrees with every place of that
    colour, so a rule counts only once it explains cells of two colours or more (each a fifth)."""

    shape: tuple[int, int]
    gain: dict = field(default_factory=dict)  # family -> int array [16, bins]
    loss: dict = field(default_factory=dict)  # family -> int array [bins]
    clicks: dict = field(default_factory=dict)  # family -> int array [bins]

    def _bins(self, family: tuple) -> int:
        H, W = self.shape
        if family[0] == "copy":
            return (2 * H - 1) * (2 * W - 1)
        return 2 * (W if family[0] == "mirror-x" else H) - 1

    def add(self, before: np.ndarray, after: np.ndarray, mask: np.ndarray | None) -> bool:
        """Fold one click's changes in; False when it changed nothing readable."""
        if before.shape != self.shape or after.shape != self.shape:
            return False
        changed = before != after
        if mask is not None:
            changed &= ~mask
        ys, xs = np.nonzero(changed)
        if not len(ys) or len(ys) > 400:
            return False
        if len(ys) > COPY_MAX_CELLS:
            pick = np.linspace(0, len(ys) - 1, COPY_MAX_CELLS).astype(int)
            ys, xs = ys[pick], xs[pick]
        stable = ~changed if mask is None else ~changed & ~mask
        H, W = self.shape
        new, old = after[ys, xs], before[ys, xs]
        colours = sorted({int(c) for c in np.concatenate([new, old])})
        where = {c: np.nonzero(stable & (after == c)) for c in colours}
        families = [("copy", k) for k in COPY_SCALES] + [("mirror-x",), ("mirror-y",)]
        for fam in families:
            n = self._bins(fam)
            gain = self.gain.setdefault(fam, np.zeros((16, n), dtype=np.int32))
            loss = self.loss.setdefault(fam, np.zeros(n, dtype=np.int32))
            spoke = np.zeros(n, dtype=np.int32)
            for c in colours:
                qy, qx = where[c]
                if not len(qy):
                    continue
                for sign, sel in ((1, new == c), (-1, old == c)):
                    if not sel.any():
                        continue
                    if fam[0] == "copy":
                        k = fam[1]
                        dy = qy[None, :] - (ys[sel] // k)[:, None] + H - 1
                        dx = qx[None, :] - (xs[sel] // k)[:, None] + W - 1
                        idx = (dy * (2 * W - 1) + dx).ravel()
                    else:
                        idx_parts = []
                        for py, px in zip(ys[sel], xs[sel]):
                            same = (qy == py) if fam[0] == "mirror-x" else (qx == px)
                            idx_parts.append((qx[same] + px) if fam[0] == "mirror-x" else (qy[same] + py))
                        idx = np.concatenate(idx_parts) if idx_parts else np.zeros(0, dtype=np.int64)
                    if not len(idx):
                        continue
                    counts = np.bincount(idx, minlength=n).astype(np.int32)
                    if sign > 0:
                        gain[c % 16] += counts
                        spoke += counts > 0
                    else:
                        loss += counts
            self.clicks.setdefault(fam, np.zeros(n, dtype=np.int32))
            self.clicks[fam] += spoke > 0
        return True

    def best(self) -> tuple[tuple, int] | None:
        """The rule with the most net agreement among those that explain cells of two colours or
        more (each a fifth of what it explains) over two clicks or more, and enough cells."""
        H, W = self.shape
        out: tuple[tuple, int] | None = None
        for fam, gain in self.gain.items():
            total_gain = gain.sum(axis=0)
            net = total_gain - self.loss[fam]
            if fam == ("copy", 1):
                net[(H - 1) * (2 * W - 1) + W - 1] = 0  # no shift is no picture
            second = np.partition(gain, -2, axis=0)[-2]
            ok = (net >= COPY_MIN_GAIN) & (self.clicks[fam] >= COPY_MIN_CLICKS) & (5 * second >= total_gain)
            if not ok.any():
                continue
            cand = np.where(ok, net, -1)
            i = int(np.argmax(cand))
            v = int(cand[i])
            if fam[0] == "copy":
                rule: tuple = ("copy", fam[1], i // (2 * W - 1) - (H - 1), i % (2 * W - 1) - (W - 1))
            else:
                rule = (fam[0], 1, i, 0)
            if out is None or v > out[1]:
                out = (rule, v)
        return out


def board_rect(before: np.ndarray, after: np.ndarray, mask: np.ndarray | None) -> tuple[int, int, int, int] | None:
    """The panel holding most of the cells a click changed: the board being drawn on."""
    changed = before != after
    if mask is not None:
        changed &= ~mask
    if not changed.any():
        return None
    best, out = 0, None
    for r in panels(after):
        y, x, h, w = r
        n = int(changed[y:y + h, x:x + w].sum())
        if n > best:
            best, out = n, r
    if out is None:
        ys, xs = np.nonzero(changed)
        out = (int(ys.min()), int(xs.min()), int(ys.max() - ys.min() + 1), int(xs.max() - xs.min() + 1))
    return out


def _gap(a: Obj, b: Obj) -> int:
    dx = max(0, max(a.x1, b.x1) - min(a.x2, b.x2) - 1)
    dy = max(0, max(a.y1, b.y1) - min(a.y2, b.y2) - 1)
    return dx + dy


def generalise(action_class: object) -> object:
    """An action class up to colour: a click on a kind becomes a click on its size and shape."""
    if isinstance(action_class, tuple) and action_class and action_class[0] == "click" and action_class[1]:
        return ("click", tuple(action_class[1][1:]))
    return action_class


@dataclass
class CauseMemory:
    """For each action class, how often it moved each hypothesis's measure, and which way."""

    moves: dict[tuple, Counter] = field(default_factory=dict)  # (hyp key, action class) -> Counter
    # The same by hypothesis type and action kind, kept across levels: what a click on a kind of
    # that size and shape (any colour) did to a goal of that type in earlier levels.
    by_type: dict[tuple, Counter] = field(default_factory=dict)

    def record(self, hyp_key: tuple, action_class: object, before: int | None, after: int | None,
               hyp_type: tuple | None = None) -> None:
        if before is None or after is None:
            return
        counters = [self.moves.setdefault((hyp_key, action_class), Counter())]
        if hyp_type is not None:
            counters.append(self.by_type.setdefault((hyp_type, generalise(action_class)), Counter()))
        for c in counters:
            c["n"] += 1
            if after < before:
                c["closer"] += 1
                c["gain"] += before - after
            elif after > before:
                c["farther"] += 1
                c["loss"] += after - before

    def live(self, hyp_key: tuple) -> bool:
        """Some action has moved this measure at least once."""
        return any(k[0] == hyp_key and (c["closer"] or c["farther"]) for k, c in self.moves.items())

    def helped(self, hyp_key: tuple) -> bool:
        """Some action has moved this measure closer to its goal."""
        return any(k[0] == hyp_key and c["closer"] for k, c in self.moves.items())

    def mean_gain(self, hyp_key: tuple, action_class: object, hyp_type: tuple | None = None) -> float:
        """Mean progress of an action class on a hypothesis in this level; until it has been tried
        here, what actions of its kind did to goals of the hypothesis's type in earlier levels."""
        c = self.moves.get((hyp_key, action_class))
        if (not c or not c["n"]) and hyp_type is not None:
            c = self.by_type.get((hyp_type, generalise(action_class)))
        if not c or not c["n"]:
            return 0.0
        return (c["gain"] - c["loss"]) / c["n"]

    def best_actions(self, hyp_key: tuple) -> list[tuple[float, object]]:
        """Action classes by mean progress on this measure, most helpful first."""
        out = []
        for (hk, cls), c in self.moves.items():
            if hk == hyp_key and c["n"]:
                out.append(((c["gain"] - c["loss"]) / c["n"], cls))
        out.sort(key=lambda t: (-t[0], repr(t[1])))
        return out
